"""Export workprint source recipes to OBJ/MTL and indexed PS1 C arrays."""
import json, hashlib
from pathlib import Path
R=Path(__file__).resolve().parents[1]; A=R/'assets44'; data=json.loads((A/'models.json').read_text())
# integer hexagonal ring; 1024 = unit radius
ring=((1024,0),(512,887),(-512,887),(-1024,0),(-512,-887),(512,-887))
class Mesh:
 def __init__(self): self.v=[]; self.f=[]; self.idx={}
 def vertex(self,p,g):
  key=(*p,g)
  if key not in self.idx: self.idx[key]=len(self.v);self.v.append(key)
  return self.idx[key]
 def tri(self,a,b,c,m,g=0):
  ids=tuple(self.vertex(p,g) for p in (a,b,c)); assert len(set(ids))==3;self.f.append((*ids,m))
 def quad(self,a,b,c,d,m):self.tri(a,b,c,m);self.tri(a,c,d,m)
 def add(self,s):
  k,m,*p=s
  if k=='tri': self.tri(*p[:3],m,p[3] if len(p)>3 else 0);return
  if k=='box':
   x,y,z,w,h,l=p;a=(x-w,y-h,z-l);b=(x+w,y-h,z-l);c=(x+w,y-h,z+l);d=(x-w,y-h,z+l);e=(x-w,y+h,z-l);f=(x+w,y+h,z-l);g=(x+w,y+h,z+l);i=(x-w,y+h,z+l)
   for q in [(a,d,c,b),(e,f,g,i),(a,b,f,e),(b,c,g,f),(c,d,i,g),(d,a,e,i)]: self.quad(*q,m)
  elif k=='orb':
   x,y,z,w,h,l=p;u=[(x+dx*w//1024,y,z+dz*l//1024) for dx,dz in ring]
   for i in range(6): j=(i+1)%6; self.tri((x,y+h,z),u[i],u[j],m);self.tri((x,y-h,z),u[j],u[i],m)
  elif k=='cone':
   x,y,z,r,tx,ty,tz=p;u=[(x+dx*r//1024,y,z+dz*r//1024) for dx,dz in ring]
   for i in range(6):j=(i+1)%6;self.tri(u[i],u[j],(tx,ty,tz),m);self.tri(u[j],u[i],(x,y,z),m)
  else:raise ValueError(k)
def export():
 out=A/'obj';out.mkdir(exist_ok=True); mats=list(data['materials']);colors=[int(data['materials'][m],16) for m in mats]; h=['/* Generated by tools/assets44.py. Do not edit. */','#ifndef MODELS44_H','#define MODELS44_H','typedef struct {signed char x,y,z;unsigned char group;} Vertex44;','typedef struct {unsigned char a,b,c,mat;} Face44;','typedef struct {const Vertex44*v;const Face44*f;unsigned short nv,nf;} Model44;','static const unsigned palette44[]={'+','.join(hex((c>>16)|((c>>8&255)<<8)|((c&255)<<16)) for c in colors)+'};']; manifest={}
 (out/'materials.mtl').write_text(''.join(f'newmtl {m}\nKd {c>>16}/255\n' for m,c in [])+''.join(f'newmtl {m}\nKd {(c>>16)/255:.4f} {(c>>8&255)/255:.4f} {(c&255)/255:.4f}\n\n' for m,c in zip(mats,colors)))
 for name,recipes in data['models'].items():
  mesh=Mesh()
  for s in recipes:mesh.add(s)
  assert len(mesh.v)<256 and all(-127<=x<=127 for v in mesh.v for x in v[:3]);v=mesh.v;f=mesh.f
  lines=['# '+data['provenance'],'mtllib materials.mtl','o '+name]+[f'v {x} {y} {z}' for x,y,z,g in v];last=None
  for a,b,c,m in f:
   if m!=last:lines.append('usemtl '+m);last=m
   lines.append(f'f {a+1} {b+1} {c+1}')
  path=out/(name+'.obj');path.write_text('\n'.join(lines)+'\n');manifest[name]={'vertices':len(v),'triangles':len(f),'sha256':hashlib.sha256(path.read_bytes()).hexdigest()}
  h+=['static const Vertex44 v44_'+name+'[]={'+','.join('{'+','.join(map(str,p))+'}' for p in v)+'};','static const Face44 f44_'+name+'[]={'+','.join('{'+','.join(map(str,(a,b,c,mats.index(m))))+'}' for a,b,c,m in f)+'};',f'static const Model44 m44_{name}={{v44_{name},f44_{name},{len(v)},{len(f)}}};']
 h+=['#endif'];(R/'src/models44.h').write_text('\n'.join(h)+'\n');(A/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n');print(json.dumps(manifest,indent=2))
if __name__=='__main__':export()
